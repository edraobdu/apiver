"""CLI seam (subprocess) for `apiver alias` (ticket #53, resolving ADR
0007's second amendment). `alias` declares a new `Alias` pointing at an
already-mounted version straight into the Aggregation Root — its
conventional home — with no separate `registry.py` and no schema/docs
wiring of its own (`Alias.urls` already re-includes the target's). Every
test runs against `tests/fixtures_mount/`, first mounting `v2` (via `apiver
mount`) so there is an already-mounted version to alias, then cleaning up
whatever both commands generated afterwards.
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
FIXTURE_ROOT = REPO_ROOT / "tests" / "fixtures_mount"
API_DIR = FIXTURE_ROOT / "api"
AGGREGATION_ROOT = API_DIR / "urls.py"

# Directories that ship as part of the fixture, never generated by a test —
# anything else found under api/ after a test ran is `mount`'s own output.
_FIXTURE_ENTRIES = {"v0", "v1", "v1_0_0", "d2026_01_01", "notaversion", "__init__.py", "__pycache__"}


def _run(
    command: str, *args: str, settings: str = "tests.fixtures_mount.settings"
) -> subprocess.CompletedProcess:
    env = dict(os.environ)
    env["DJANGO_SETTINGS_MODULE"] = settings
    env["PYTHONPATH"] = os.pathsep.join([str(REPO_ROOT / "src"), str(REPO_ROOT)])
    return subprocess.run(
        [sys.executable, "-m", "apiver.cli", command, *args],
        cwd=str(REPO_ROOT),
        env=env,
        capture_output=True,
        text=True,
    )


@pytest.fixture(autouse=True)
def _clean_generated_output():
    AGGREGATION_ROOT.unlink(missing_ok=True)
    yield
    AGGREGATION_ROOT.unlink(missing_ok=True)
    for child in API_DIR.iterdir():
        if child.name not in _FIXTURE_ENTRIES:
            shutil.rmtree(child)


def _mount_v2() -> None:
    result = _run("mount", "v2", "--from", "v1")
    assert result.returncode == 0, result.stderr


def test_alias_declares_an_alias_pointing_at_the_mounted_version():
    _mount_v2()

    result = _run("alias", "stable", "--from", "v2")

    assert result.returncode == 0, result.stderr
    assert f"wrote {AGGREGATION_ROOT}" in result.stdout
    assert "add 'stable' to APIVER_ALIASES" in result.stdout

    source = AGGREGATION_ROOT.read_text()
    assert "from apiver.drf import Alias" in source
    assert "stable = Alias('stable', target=v2)" in source
    assert "    path('api/stable/', stable.urls)," in source
    # No include() wrapper — Alias.urls already returns one.
    assert "include(stable.urls)" not in source


