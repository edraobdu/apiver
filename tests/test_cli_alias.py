def test_alias_refuses_to_declare_the_same_alias_twice():
    _mount_v2()
    first = _run("alias", "stable", "--from", "v2")
    assert first.returncode == 0, first.stderr
    written = AGGREGATION_ROOT.read_text()

    second = _run("alias", "stable", "--from", "v2")

    assert second.returncode != 0
    assert "already mounted" in second.stderr
    assert AGGREGATION_ROOT.read_text() == written


def test_alias_extends_an_aggregation_root_that_already_has_an_alias():
    _mount_v2()
    first = _run("alias", "stable", "--from", "v2")
    assert first.returncode == 0, first.stderr

    second = _run("alias", "latest", "--from", "v2")

    assert second.returncode == 0, second.stderr
    source = AGGREGATION_ROOT.read_text()
    # The Alias import is only ever appended once.
    assert source.count("from apiver.drf import Alias") == 1
    assert "stable = Alias('stable', target=v2)" in source
    assert "latest = Alias('latest', target=v2)" in source
    assert "    path('api/stable/', stable.urls)," in source
    assert "    path('api/latest/', latest.urls)," in source


def test_alias_refuses_a_scheme_nonconforming_from():
    """ticket #67, ADR 0008 item 5: `--from` is validated against the
    configured scheme even though it already resolves to a real, mounted
    Version — modeling a project that mounted 'v2' under `sequential` and
    only later switched APIVER_VERSION_SCHEME to `semver`, under which
    'v2' no longer conforms."""
    _mount_v2()

    result = _run("alias", "stable", "--from", "v2", settings="tests.fixtures_mount.settings_semver")

    assert result.returncode != 0
    assert "--from 'v2' does not conform" in result.stderr
    assert "APIVER_VERSION_SCHEME='semver'" in result.stderr
    assert "stable" not in AGGREGATION_ROOT.read_text()


def test_alias_name_stays_exempt_from_scheme_validation():
    """ADR 0008 item 5: an alias name is a human label ('stable'), not a
    version point — it's never checked against the scheme, even a strict
    one under which it could never conform, and its own literal URL
    segment keeps that raw name, unformatted."""
    mounted = _run("mount", "v1_1_0", "--from", "v1_0_0", settings="tests.fixtures_mount.settings_semver")
    assert mounted.returncode == 0, mounted.stderr

    result = _run("alias", "stable", "--from", "v1_1_0", settings="tests.fixtures_mount.settings_semver")

    assert result.returncode == 0, result.stderr
    source = AGGREGATION_ROOT.read_text()
    assert "stable = Alias('stable', target=v1_1_0)" in source
    assert "    path('api/stable/', stable.urls)," in source


